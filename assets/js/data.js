/* строка прайса в разметке (используется страницами услуг и «Ценами»). Примечание — отдельным
   элементом после цены: внутри названия оно расширяло бы колонку названия, и лидер начинался
   бы много правее текста, а на мобильном цена падала под примечание */
const priceRowHTML = (r) => `<div class="price-row"><span class="nm">${r.n}</span><span class="ln"></span><span class="vl">${r.v}</span>${r.sub ? `<small>${r.sub}</small>` : ''}</div>`;

/* заголовок рубрики на «Ценах»: «от N ₽», где N — цена строки leadRow.
   Минимум по всем строкам не годится: самая дешёвая строка рубрики — сопутствующая
   (коффердам 590 ₽, снятие слепков 2 100 ₽), и её цена в заголовке читается
   как цена всей рубрики. Нет lead — пустой заголовок (ловит checks/gates.mjs),
   а не ошибка на странице. */
const rubFrom = (b) => {
  const lead = b.rows.find(r => r.id === b.leadRow);
  return lead ? 'от ' + lead.v.replace(/^от\s+/, '') : '';
};
